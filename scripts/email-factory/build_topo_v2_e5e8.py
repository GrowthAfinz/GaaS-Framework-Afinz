def compile_source(source):
    rows = list(csv.reader(source.open(encoding='utf-8-sig', newline=''), delimiter=';'))
    stop = next(i for i, row in enumerate(rows) if row and row[0].startswith('2 ·'))
    first = rows[:stop]
    def value(field, number):
        row = next(row for row in first if len(row) > 3 and row[2] == field)
        return row[number + 3].replace('\xa0', ' ').strip()
    def clean(text):
        return (text.replace('\r\n', '<br>').replace('\n', '<br>')
                .replace('+amigoAfinz', '+amigo Afinz').replace('te da vantagens', 'te dá vantagens')
                .replace('simpels', 'simples'))
    emails = []
    for number in range(5, 9):
        patch = {field: clean(value(field, number)) for field in
                 ['ASSUNTO', 'PRE_CABECALHO', 'COPY_1_PRETO', 'TITULO_COPY_2']}
        patch.update({
            'HEADER': '',
            'HEADER_TITULO': value('TB_HEADER_VARIACOES · TITULO', number),
            'HEADER_SUBTITULO': value('TB_HEADER_VARIACOES · SUBTITULO', number),
            'HEADER_IMAGEM_CARTAO': value('TB_HEADER_VARIACOES · IMAGEM_CARTAO', number),
            'TITULO_COPY_1_AZUL': 'Olá, %%=v(@FirstName)=%%!',
            'BANNER_1_CORPO': '', 'BANNER_2_CORPO': '',
        })
        if number == 6:
            patch['HEADER_TITULO'] = 'Mais cuidado para sua saúde'
        if number == 8:
            patch['ASSUNTO'] = 'Peça seu cartão +amigo e aproveite as vantagens'
        lines = [line.strip() for line in clean(value('BANNER_1_CORPO', number)).split('<br>') if line.strip()]
        intro = lines.pop(0)
        items = [re.sub(r'^[^\w+]+', '', line).strip() for line in lines]
        blocks = [{'type': 'lead', 'text': intro}, {'type': 'check_list', 'items': items},
                  {'type': 'closing', 'text': clean(value('COPY_2_PRETO', number))}]
        patch['COPY_2_PRETO'] = lead(intro) + check_list(items) + closing(blocks[-1]['text'])
        if number == 7:
            title_lines = patch['TITULO_COPY_2'].split('<br>')
            step_items = [{'title': re.sub(r'^\d\ufe0f?\u20e3\s*', '', line), 'text': ''}
                          for line in title_lines[1:]]
            assert len(step_items) == 4
            patch['TITULO_COPY_2'] = title_lines[0].rstrip(':')
            # Keep all the marketing text within the DE's 4000-character limit.
            benefits_text = intro + '<br>' + '<br>'.join(items)
            blocks = [{'type': 'steps', 'items': step_items},
                      {'type': 'lead', 'text': benefits_text}, blocks[-1]]
            patch['COPY_2_PRETO'] = (steps([(item['title'], item['text']) for item in step_items])
                                    + lead(benefits_text) + closing(blocks[-1]['text']))
        assert all(len(v) <= 4000 and '\n' not in v for v in patch.values())
        emails.append({'number': number, 'week': (number + 1) // 2,
                       'day': 1 if number % 2 else 2, 'patch': patch, 'secondBlock': blocks})
    return {'source': source.name, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
            'section': 1, 'segment': 'V2 TOPO DE FUNIL DINÂMICO', 'emails': emails}

